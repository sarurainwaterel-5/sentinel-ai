#!/usr/bin/env python3
"""Index markdown notes into viewer/graph-data.js for the knowledge galaxy.

Standard library only. Usage:
    python3 build.py [NOTES_DIR]      # default: ../docs (Sentinel's docs tree)

Every node's numeric `id` equals its index in GRAPH.nodes; the server and the
viewer both look nodes up by that index.
"""
import json
import os
import re
import subprocess
import sys
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_NOTES = HERE.parent / "docs"
OUT = HERE / "viewer" / "graph-data.js"
EXCERPT_CHARS = 700
SKIP_DIRS = {"node_modules", ".git", ".venv", "venv", "__pycache__", ".pytest_cache", "galaxy"}
WIKILINK = re.compile(r"\[\[([^\]|#]+)(?:[#|][^\]]*)?\]\]")
MIN_TITLE_LEN = 5  # avoid linking on tiny generic titles like "README"
GENERIC_TITLES = {"readme", "index", "notes", "agents"}


def label_from_filename(path: Path) -> str:
    return re.sub(r"[-_]+", " ", path.stem).strip()


def norm(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", " ", text.lower()).strip()


def make_excerpt(text: str) -> str:
    text = re.sub(r"^---\n.*?\n---\n", "", text, flags=re.S)  # front matter
    text = re.sub(r"```.*?```", " ", text, flags=re.S)  # code fences
    text = re.sub(r"\s+", " ", text).strip()
    if len(text) <= EXCERPT_CHARS:
        return text
    cut = text[:EXCERPT_CHARS]
    return cut[: cut.rfind(" ")] + " …" if " " in cut else cut


def sentinel_api_url():
    """Sentinel API base URL: config.json's sentinel_api_url, else the docker container IP."""
    cfg_path = HERE / "config.json"
    if cfg_path.exists():
        url = json.loads(cfg_path.read_text()).get("sentinel_api_url")
        if url:
            return url.rstrip("/")
    return discover_sentinel_api()


def discover_sentinel_api():
    try:
        ip = subprocess.run(
            ["docker", "inspect", "-f", "{{range .NetworkSettings.Networks}}{{.IPAddress}} {{end}}",
             "sentinel-local-api-1"], capture_output=True, text=True, timeout=10).stdout.split()
        return f"http://{ip[0]}:8000" if ip else None
    except (OSError, subprocess.SubprocessError):
        return None


def fetch_taught_documents():
    for base in dict.fromkeys([sentinel_api_url(), discover_sentinel_api()]):
        if not base:
            continue
        try:
            with urllib.request.urlopen(f"{base}/documents", timeout=15) as r:
                docs = json.load(r)
            docs = [d for d in docs if d.get("status", "indexed") == "indexed"]
            return sorted(docs, key=lambda d: (d.get("module") or "", d["filename"].lower()))
        except (OSError, ValueError):
            continue
    print("warning: Sentinel API unreachable; taught documents not included", file=sys.stderr)
    return []


def scan(root: Path):
    files = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS and not d.startswith("."))
        for name in sorted(filenames):
            if name.lower().endswith(".md"):
                files.append(Path(dirpath) / name)
    return files


def signature(root: Path, taught):
    """Fingerprint of everything the graph is built from (notes + taught catalog)."""
    import hashlib
    h = hashlib.sha256()
    for f in scan(root):
        st = f.stat()
        h.update(f"{f.relative_to(root)}|{st.st_mtime_ns}|{st.st_size}\n".encode())
    for d in taught:
        h.update(f"T|{d['filename']}|{d.get('module')}|{d.get('topic')}|{d.get('chunk_count')}\n".encode())
    return h.hexdigest()[:16]


def write_graph(graph, version=""):
    OUT.parent.mkdir(parents=True, exist_ok=True)
    tmp = OUT.with_suffix(".tmp")
    tmp.write_text(
        "// Generated by build.py — do not edit.\nconst GRAPH = "
        + json.dumps({**graph, "version": version}, ensure_ascii=False) + ";\n",
        encoding="utf-8")
    tmp.replace(OUT)  # atomic swap so the browser never reads a half-written file


def build(root: Path, taught=None):
    files = scan(root)
    nodes, bodies, wikis = [], [], []
    for i, path in enumerate(files):
        text = path.read_text(encoding="utf-8", errors="replace")
        rel = path.relative_to(root)
        group = rel.parent.name if rel.parent != Path(".") else root.name
        nodes.append({
            "id": i,
            "label": label_from_filename(path),
            "group": group,
            "path": str(rel),
            "excerpt": make_excerpt(text),
        })
        bodies.append(" " + norm(text) + " ")
        wikis.append({norm(w) for w in WIKILINK.findall(text)})

    titles = [norm(n["label"]) for n in nodes]
    stems = [norm(Path(n["path"]).stem) for n in nodes]
    links = set()

    for i in range(len(nodes)):
        for j in range(len(nodes)):
            if i == j:
                continue
            t = titles[j]
            # A mentions B's title (or B's file stem via a wikilink)
            mentions = (
                len(t) >= MIN_TITLE_LEN and t not in GENERIC_TITLES and f" {t} " in bodies[i]
            ) or t in wikis[i] or stems[j] in wikis[i]
            # A and B share a wikilink target
            shared = bool(wikis[i] & wikis[j]) if i < j else False
            if mentions or shared:
                links.add((min(i, j), max(i, j)))

    # Documents Sentinel was taught (Teach / upload), from its own API.
    if taught is None:
        taught = fetch_taught_documents()
    hubs = {}
    for doc in taught:
        i = len(nodes)
        module = doc.get("module") or "general"
        topic = doc.get("topic") or "general"
        nodes.append({
            "id": i,
            "label": label_from_filename(Path(doc["filename"])),
            "group": f"taught · {module}",
            "path": doc["filename"],
            "taught": True,
            "excerpt": (f"Taught to Sentinel ({module}"
                        + (f" / {topic}" if topic != "general" else "")
                        + f"). {doc.get('chunk_count', 0)} indexed passages. "
                        "Ask a question to pull the relevant passages from this source."),
        })
        if module in hubs:  # star each module's sources around its first one
            links.add((hubs[module], i))
        else:
            hubs[module] = i
    if taught:
        # Tie each taught module to markdown notes that name it as a group/title word.
        for module, hub in hubs.items():
            for j in range(len(titles)):
                if module in titles[j].split() or nodes[j]["group"].lower() == module:
                    links.add((j, hub))

    link_list = [{"source": a, "target": b} for a, b in sorted(links)]
    for idx, n in enumerate(nodes):
        assert n["id"] == idx
    return {"nodes": nodes, "links": link_list}


def main():
    root = Path(sys.argv[1]).expanduser().resolve() if len(sys.argv) > 1 else DEFAULT_NOTES
    if not root.is_dir():
        sys.exit(f"Notes folder not found: {root}")
    taught = fetch_taught_documents()
    graph = build(root, taught)
    write_graph(graph, signature(root, taught))
    groups = sorted({n["group"] for n in graph["nodes"]})
    print(f"Indexed {len(graph['nodes'])} notes, {len(graph['links'])} links, "
          f"{len(groups)} groups from {root}\n-> {OUT}")


if __name__ == "__main__":
    main()
